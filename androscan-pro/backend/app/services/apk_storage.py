from __future__ import annotations

import os
import shutil
from pathlib import Path, PurePosixPath

import boto3
from botocore.exceptions import ClientError

from app.core.config import get_settings


class ObjectStorageError(RuntimeError):
    pass


class S3ObjectStorage:
    """Storage adapter: local shared volume for development, S3-compatible for deployment."""

    def __init__(self) -> None:
        settings = get_settings()
        self.backend = settings.storage_backend.strip().lower()
        self.bucket = settings.s3_bucket
        self.local_root = Path(settings.local_storage_path).resolve()
        self.client = None
        if self.backend == "s3":
            self.client = boto3.client(
                "s3",
                endpoint_url=settings.s3_endpoint,
                aws_access_key_id=settings.s3_access_key,
                aws_secret_access_key=settings.s3_secret_key,
                region_name=settings.s3_region,
            )
        elif self.backend != "local":
            raise ObjectStorageError("STORAGE_BACKEND debe ser 'local' o 's3'")

    def _local_path(self, key: str) -> Path:
        # Storage keys are generated by the API, but still validate them at the boundary.
        relative = PurePosixPath(key)
        if relative.is_absolute() or not relative.parts or any(part in {"", ".", ".."} for part in relative.parts):
            raise ObjectStorageError("Clave de almacenamiento no válida")
        target = (self.local_root / Path(*relative.parts)).resolve()
        if target != self.local_root and self.local_root not in target.parents:
            raise ObjectStorageError("Clave de almacenamiento fuera del directorio permitido")
        return target

    def ensure_bucket(self) -> None:
        if self.backend == "local":
            self.local_root.mkdir(parents=True, exist_ok=True)
            return
        assert self.client is not None
        try:
            self.client.head_bucket(Bucket=self.bucket)
        except ClientError as exc:
            error_code = str(exc.response.get("Error", {}).get("Code", ""))
            if error_code not in {"404", "NoSuchBucket", "NotFound"}:
                raise ObjectStorageError("No fue posible comprobar el bucket") from exc
            try:
                self.client.create_bucket(Bucket=self.bucket)
            except ClientError as create_exc:
                raise ObjectStorageError("No fue posible crear el bucket") from create_exc

    def download_to_file(self, key: str, destination: str) -> None:
        try:
            self.ensure_bucket()
            if self.backend == "local":
                source = self._local_path(key)
                if not source.is_file():
                    raise ObjectStorageError("El APK no existe en el almacenamiento local")
                Path(destination).parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, destination)
            else:
                assert self.client is not None
                self.client.download_file(self.bucket, key, destination)
        except Exception as exc:
            if isinstance(exc, ObjectStorageError):
                raise
            raise ObjectStorageError("No fue posible recuperar el APK") from exc

    def put_fileobj(self, key: str, fileobj, *, content_type: str, content_length: int) -> None:
        try:
            self.ensure_bucket()
            if self.backend == "local":
                target = self._local_path(key)
                target.parent.mkdir(parents=True, exist_ok=True)
                with target.open("wb") as output:
                    shutil.copyfileobj(fileobj, output)
            else:
                assert self.client is not None
                self.client.upload_fileobj(
                    fileobj,
                    self.bucket,
                    key,
                    ExtraArgs={"ContentType": content_type},
                )
        except Exception as exc:
            if isinstance(exc, ObjectStorageError):
                raise
            raise ObjectStorageError("No fue posible almacenar el APK") from exc
